"""Run pytest in a subprocess and read per-test outcomes and coverage.

Generated suites run sandboxed: a temporary directory, a timeout, an environment
without credential variables, and Python-level network access disabled.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path
from typing import Protocol

from .error import RunnerError

DEFAULT_TIMEOUT = 60
GENERATED_HEADER = "# generated by reviewer test-gen"
MESSAGE_LIMIT = 1500

_SECRET_WORDS = ("KEY", "TOKEN", "SECRET", "PASSWORD", "PASSWD", "CREDENTIAL", "AUTH")

SANDBOX_PLUGIN = '''\
"""Loaded with -p by reviewer: blocks network access and can reverse test order."""
import os
import socket


def _blocked(*args, **kwargs):
    raise RuntimeError("network access is disabled while running generated tests")


socket.socket.connect = _blocked
socket.socket.connect_ex = _blocked
socket.create_connection = _blocked


def pytest_collection_modifyitems(session, config, items):
    if os.environ.get("REVIEWER_REVERSE") == "1":
        items.reverse()
'''

# Outcome names, worst first: the aggregate for a parametrized test is its worst case.
OUTCOME_ORDER = ("failed", "xpassed", "skipped", "xfailed", "passed")


@dataclass
class RunResult:
    outcomes: dict[str, str] = field(default_factory=dict)
    messages: dict[str, str] = field(default_factory=dict)
    coverage: dict[str, float] = field(default_factory=dict)
    collection_error: str | None = None
    timed_out: bool = False

    @property
    def ok(self) -> bool:
        return not self.timed_out and self.collection_error is None

    def with_outcome(self, *outcomes: str) -> list[str]:
        return [name for name, outcome in self.outcomes.items() if outcome in outcomes]


class TestRunner(Protocol):
    __test__ = False

    def run_generated(
        self, code: str, file_name: str, targets: list[Path], reverse: bool = False
    ) -> RunResult: ...

    def run_existing(self, test_paths: list[Path], targets: list[Path]) -> RunResult: ...


def is_secret_var(name: str) -> bool:
    upper = name.upper()
    return upper.startswith("ANTHROPIC_") or any(word in upper for word in _SECRET_WORDS)


def clean_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = {key: value for key, value in os.environ.items() if not is_secret_var(key)}
    env.pop("PYTHONPATH", None)
    env.update({"PYTHONDONTWRITEBYTECODE": "1", "PYTHONHASHSEED": "0"})
    env.update(extra or {})
    return env


def _trim(text: str) -> str:
    text = text.strip()
    return text if len(text) <= MESSAGE_LIMIT else "…" + text[-MESSAGE_LIMIT:]


def _test_key(case: ET.Element) -> str:
    base = case.get("name", "").split("[", 1)[0]
    owner = case.get("classname", "").split(".")[-1]
    return f"{owner}.{base}" if owner.startswith("Test") else base


def parse_junit(path: Path) -> tuple[dict[str, str], dict[str, str], str | None]:
    """Return (outcome per test function, failure message per test, collection error)."""
    outcomes: dict[str, str] = {}
    messages: dict[str, str] = {}
    collection_error: str | None = None
    for case in ET.parse(path).getroot().iter("testcase"):
        failure = case.find("failure")
        error = case.find("error")
        skipped = case.find("skipped")
        if error is not None and not case.get("classname"):
            collection_error = _trim(error.get("message", "") + "\n" + (error.text or ""))
            continue
        problem = failure if failure is not None else error
        if problem is not None:
            outcome = "xpassed" if "XPASS" in problem.get("message", "") else "failed"
            messages[_test_key(case)] = _trim(
                problem.get("message", "") + "\n" + (problem.text or "")
            )
        elif skipped is not None:
            outcome = "xfailed" if skipped.get("type") == "pytest.xfail" else "skipped"
        else:
            outcome = "passed"
        key = _test_key(case)
        previous = outcomes.get(key)
        if previous is None or OUTCOME_ORDER.index(outcome) < OUTCOME_ORDER.index(previous):
            outcomes[key] = outcome
    return outcomes, messages, collection_error


def parse_coverage(path: Path, cwd: Path, targets: list[Path]) -> dict[str, float]:
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    wanted = {target.resolve() for target in targets}
    found: dict[str, float] = {}
    for name, info in data.get("files", {}).items():
        resolved = (cwd / name).resolve()
        if resolved in wanted:
            found[resolved.as_posix()] = round(info["summary"]["percent_covered"], 2)
    return found


@dataclass
class SubprocessRunner:
    root: Path
    timeout: int = DEFAULT_TIMEOUT
    existing_timeout: int = 300

    def _run(
        self,
        args: list[str],
        cwd: Path,
        work: Path,
        targets: list[Path],
        env: dict[str, str],
        timeout: int,
    ) -> RunResult:
        junit = work / "junit.xml"
        cov_json = work / "coverage.json"
        cov_dirs = sorted({str(t.resolve().parent) for t in targets})
        command = [
            sys.executable,
            "-m",
            "pytest",
            *args,
            "-q",
            "-p",
            "no:cacheprovider",
            f"--junitxml={junit}",
            *[f"--cov={d}" for d in cov_dirs],
            f"--cov-report=json:{cov_json}",
        ]
        try:
            completed = subprocess.run(
                command,
                cwd=cwd,
                env=env,
                capture_output=True,
                text=True,
                timeout=timeout,
            )
        except subprocess.TimeoutExpired:
            return RunResult(timed_out=True)
        except OSError as exc:
            raise RunnerError(f"could not start pytest: {exc}") from exc

        if not junit.is_file():
            if completed.returncode == 2 or completed.returncode == 5:
                output = completed.stdout + completed.stderr
                return RunResult(collection_error=_trim(output) or "no tests collected")
            raise RunnerError(
                f"pytest failed (exit {completed.returncode}): {_trim(completed.stderr)}"
            )

        outcomes, messages, collection_error = parse_junit(junit)
        if completed.returncode == 5 or (not outcomes and collection_error is None):
            collection_error = "no tests collected"
        return RunResult(
            outcomes=outcomes,
            messages=messages,
            coverage=parse_coverage(cov_json, cwd, targets),
            collection_error=collection_error,
        )

    def run_generated(
        self, code: str, file_name: str, targets: list[Path], reverse: bool = False
    ) -> RunResult:
        with tempfile.TemporaryDirectory(prefix="reviewer-test-gen-") as tmp:
            work = Path(tmp)
            (work / "pytest.ini").write_text("[pytest]\n", encoding="utf-8")
            (work / "reviewer_sandbox.py").write_text(SANDBOX_PLUGIN, encoding="utf-8")
            (work / file_name).write_text(code, encoding="utf-8")
            env = clean_env(
                {
                    "PYTHONPATH": os.pathsep.join([str(self.root.resolve()), str(work)]),
                    "REVIEWER_REVERSE": "1" if reverse else "0",
                }
            )
            args = [file_name, "-c", "pytest.ini", "-p", "reviewer_sandbox"]
            return self._run(args, work, work, targets, env, self.timeout)

    def run_existing(self, test_paths: list[Path], targets: list[Path]) -> RunResult:
        with tempfile.TemporaryDirectory(prefix="reviewer-tests-") as tmp:
            env = clean_env({"PYTHONPATH": str(self.root.resolve())})
            args = [str(path) for path in test_paths]
            return self._run(args, self.root, Path(tmp), targets, env, self.existing_timeout)
