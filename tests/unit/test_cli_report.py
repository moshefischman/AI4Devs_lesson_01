import io
import shutil
from pathlib import Path

import pytest

from reviewer import cli
from reviewer.error import ApiError, RunnerError
from reviewer.model import QualityReport, TestSuite
from tests.factory import FakeGenClient, FakeRunner, chunk_response, gen_suite, raw_finding

ROOT = Path(__file__).resolve().parents[2]
SAMPLE = ROOT / "tests" / "fixtures" / "sample_module.py"
CODE = "def test_clamp_happy():\n    pass\n\ndef test_clamp_failure():\n    pass\n"


@pytest.fixture(autouse=True)
def _no_dotenv(monkeypatch):
    monkeypatch.setattr(cli, "load_dotenv", lambda: None)


@pytest.fixture
def project(tmp_path):
    """A copy of the sample module in an isolated project root."""
    (tmp_path / "pkg").mkdir()
    shutil.copy(SAMPLE, tmp_path / "pkg" / "sample_module.py")
    return tmp_path


def _run(argv, client=None, runner=None):
    out, err = io.StringIO(), io.StringIO()
    client = client or FakeGenClient([gen_suite(CODE)])
    runner = runner or FakeRunner()
    code = cli.main(
        argv,
        client_factory=lambda args: client,
        runner_factory=lambda args: runner,
        stdin=io.StringIO(""),
        stdout=out,
        stderr=err,
    )
    return code, out.getvalue(), err.getvalue()


def _report_args(project, *extra):
    return [
        "report",
        str(project / "pkg"),
        "--root",
        str(project),
        "--out",
        str(project / "out"),
        *extra,
    ]


def test_report_json_validates_against_the_quality_report_schema(project):
    code, out, err = _run(_report_args(project, "--format", "json"))
    report = QualityReport.model_validate_json(out)
    assert code == cli.EXIT_OK
    assert report.verdict.value == "pass"
    assert sorted(p.suffix for p in (project / "out").iterdir()) == [".json", ".md"]
    assert "wrote" in err


def test_report_exits_one_when_verdict_reaches_threshold(project):
    def handler(content):
        return chunk_response([raw_finding(file="pkg/sample_module.py", severity="critical")])

    client = FakeGenClient([gen_suite(CODE)], handler=handler)
    code, out, _ = _run(_report_args(project), client=client)
    assert code == cli.EXIT_FINDINGS
    assert "FAIL" in out


def test_fail_on_verdict_warn_is_stricter(project):
    # Two high findings, no coverage/tests measured: review 60, static 100 -> ~71 = warn
    def handler(content):
        return chunk_response(
            [
                raw_finding(file="pkg/sample_module.py", line_start=8, line_end=8, title="A"),
                raw_finding(file="pkg/sample_module.py", line_start=9, line_end=9, title="B"),
            ]
        )

    client = FakeGenClient([gen_suite(CODE)], handler=handler)
    lenient, _, _ = _run(_report_args(project), client=client)
    strict, _, _ = _run(_report_args(project, "--fail-on-verdict", "warn"), client=client)
    assert (lenient, strict) == (cli.EXIT_OK, cli.EXIT_FINDINGS)


def test_report_api_error_exits_three(project):
    client = FakeGenClient(
        [gen_suite(CODE)], handler=lambda c: ApiError("Claude API error (status 500)")
    )
    code, _, err = _run(_report_args(project), client=client)
    assert code == 3
    assert "status 500" in err


def test_test_gen_writes_only_inside_out_dir(project):
    out_dir = project / "out"
    code, out, _ = _run(
        [
            "test-gen",
            str(project / "pkg" / "sample_module.py"),
            "--root",
            str(project),
            "--out",
            str(out_dir),
        ]
    )

    assert code == cli.EXIT_OK
    assert "2 passed, 0 xfail, 0 discarded" in out
    written = sorted(p.relative_to(project).as_posix() for p in project.rglob("*") if p.is_file())
    assert [p for p in written if not p.startswith(("out/", "pkg/"))] == []
    suite_json = next(out_dir.rglob("*.suite.json"))
    assert (
        TestSuite.model_validate_json(suite_json.read_text(encoding="utf-8")).test_file
        == "test_sample_module.py"
    )


def test_test_gen_apply_copies_without_overwriting(project):
    argv = [
        "test-gen",
        str(project / "pkg" / "sample_module.py"),
        "--root",
        str(project),
        "--out",
        str(project / "out"),
        "--apply",
    ]

    first, _, err = _run(argv)
    applied = project / "tests" / "unit" / "test_sample_module.py"
    assert first == cli.EXIT_OK
    assert applied.read_text(encoding="utf-8").startswith("# generated by reviewer test-gen")

    applied.write_text("# my own tests\n", encoding="utf-8")
    second, _, err = _run(argv)
    assert second == cli.EXIT_USAGE
    assert "not overwritten" in err
    assert applied.read_text(encoding="utf-8") == "# my own tests\n"


def test_test_gen_runner_error_exits_four(project):
    class BrokenRunner(FakeRunner):
        def run_generated(self, *args, **kwargs):
            raise RunnerError("could not start pytest")

    code, _, err = _run(
        [
            "test-gen",
            str(project / "pkg" / "sample_module.py"),
            "--root",
            str(project),
            "--out",
            str(project / "out"),
        ],
        runner=BrokenRunner(),
    )
    assert code == 4
    assert "could not start pytest" in err


def test_test_gen_rejects_non_python_target(project):
    (project / "app.js").write_text("x\n", encoding="utf-8")
    code, _, err = _run(["test-gen", str(project / "app.js"), "--root", str(project)])
    assert code == cli.EXIT_USAGE
    assert "Python" in err
